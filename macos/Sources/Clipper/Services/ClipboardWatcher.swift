import AppKit
import ClipperCore
import os

/// Polls `NSPasteboard.general.changeCount` (there is no notification API on
/// macOS) and hands complete, verbatim snapshots to the Rust engine.
///
/// Fidelity: *every* flavour of *every* pasteboard item is captured with
/// `data(forType:)` and stored unchanged. Clipper never re-encodes text, so
/// Markdown, tab-separated cells, RTF, HTML, private app types and images all
/// come back exactly as they were copied.
@MainActor
final class ClipboardWatcher {
    /// Marker we add when *we* write the pasteboard, so our own paste is not
    /// re-ingested as a new copy.
    static let fromClipperType = NSPasteboard.PasteboardType("com.kkrishnan90.clipper.from-clipper")
    /// Cross-app conventions from http://nspasteboard.org
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")

    /// Flavours never worth persisting.
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        fromClipperType, concealedType, transientType, autoGeneratedType, sourceType,
        NSPasteboard.PasteboardType("com.apple.finder.noderef"),
        NSPasteboard.PasteboardType("com.apple.icns"),
    ]
    private static let microsoftSourcePrefix = "com.microsoft.ole.source"

    private let pasteboard = NSPasteboard.general
    private let core: CoreService
    private var timer: Timer?
    private var lastChangeCount: Int
    private var ignoredUntilChangeCount = -1
    private let log = Logger(subsystem: "com.kkrishnan90.clipper", category: "watcher")

    var isPaused = false {
        didSet { if !isPaused { lastChangeCount = pasteboard.changeCount } }
    }

    init(core: CoreService) {
        self.core = core
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        stop()
        let ms = max(100, UserDefaults.standard.integer(forKey: PrefKey.clipboardCheckIntervalMs))
        let t = Timer(timeInterval: Double(ms) / 1000, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.checkForChanges() }
        }
        t.tolerance = 0.1
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Call right after writing the pasteboard ourselves.
    func skipNextChange() {
        ignoredUntilChangeCount = pasteboard.changeCount
    }

    func checkForChanges() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard !isPaused, count != ignoredUntilChangeCount else { return }

        guard let items = pasteboard.pasteboardItems, !items.isEmpty else { return }
        let allTypes = Set(items.flatMap(\.types))
        if allTypes.contains(Self.fromClipperType) { return }

        let source = NSWorkspace.shared.frontmostApplication
        if let bundle = source?.bundleIdentifier, shouldIgnore(bundle) { return }

        var flavors: [Flavor] = []
        var concealed = allTypes.contains(Self.concealedType)
        let transient = allTypes.contains(Self.transientType) || allTypes.contains(Self.autoGeneratedType)

        // Some apps (BBEdit, Edge) put two items on the pasteboard for one
        // copy; flatten everything into one record, exactly as Maccy does.
        for item in items {
            var types = item.types.filter { !Self.skippedTypes.contains($0) }
            types.removeAll { $0.rawValue.hasPrefix(Self.microsoftSourcePrefix) }
            // Word bookmarks / cross-references masquerade as links + PDF.
            let msLink = NSPasteboard.PasteboardType("com.microsoft.Link-Source")
            let msObject = NSPasteboard.PasteboardType("com.microsoft.ObjectLink")
            if types.contains(msLink), types.contains(msObject) {
                types.removeAll { $0 == msLink || $0 == msObject || $0 == .pdf }
            }
            for type in types {
                guard let data = item.data(forType: type) else { continue }
                flavors.append(Flavor(uti: type.rawValue, data: data))
            }
        }
        guard !flavors.isEmpty else { return }

        // Password managers that predate nspasteboard.org: treat as concealed.
        if let bundle = source?.bundleIdentifier, CoreService.knownSecretApps.contains(bundle) {
            concealed = true
        }

        let sourceApp = source.map {
            SourceApp(name: $0.localizedName ?? $0.bundleIdentifier ?? "Unknown", bundleId: $0.bundleIdentifier)
        }
        let snapshot = Snapshot(flavors: flavors, source: sourceApp, concealed: concealed, transient: transient)
        log.debug("captured \(flavors.count) flavours from \(sourceApp?.name ?? "?")")
        core.ingest(snapshot)
    }

    private func shouldIgnore(_ bundleId: String) -> Bool {
        let d = UserDefaults.standard
        let listed = (d.stringArray(forKey: PrefKey.ignoredApps) ?? []).contains(bundleId)
        return d.bool(forKey: PrefKey.ignoreAllAppsExceptListed) ? !listed : listed
    }
}
